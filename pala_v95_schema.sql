create or replace function public.admin_delete_employee(p_token text, p_id bigint)
returns void
language plpgsql security definer set search_path = public, pg_temp
as $$
declare v_admin record; v_target_admin boolean;
begin
  select * into v_admin from public.pala_session_employee(p_token) limit 1;
  if v_admin.employee_id is null or not v_admin.is_admin then raise exception 'Administratorlogin kræves'; end if;
  if p_id=v_admin.employee_id then raise exception 'Du kan ikke slette dig selv'; end if;
  select is_admin into v_target_admin from public.employees where id=p_id;
  if coalesce(v_target_admin,false) and lower(btrim(v_admin.employee_name))<>'lukas' then raise exception 'Kun Lukas kan fjerne en administrator'; end if;
  delete from public.employees where id=p_id;
end;
$$;

create or replace function public.admin_save_booking(
  p_token text,p_id bigint,p_order_no text,p_customer_name text,p_title text,p_start_date date,p_end_date date,
  p_delivery_date date,p_pickup_date date,p_status text,p_color text,p_notes text,p_tents jsonb,p_inventory jsonb
)
returns bigint
language plpgsql security definer set search_path = public, pg_temp
as $$
declare v_admin record; v_id bigint;
begin
  select * into v_admin from public.pala_session_employee(p_token) limit 1;
  if v_admin.employee_id is null or not v_admin.is_admin then raise exception 'Administratorlogin kræves'; end if;
  if p_start_date is null or p_end_date is null or p_end_date<p_start_date then raise exception 'Kontrollér brugsperioden'; end if;
  if p_id is null then
    insert into public.bookings(order_no,customer_name,title,start_date,end_date,delivery_date,pickup_date,status,color,notes)
    values(nullif(btrim(p_order_no),''),nullif(btrim(p_customer_name),''),nullif(btrim(p_title),''),p_start_date,p_end_date,p_delivery_date,p_pickup_date,coalesce(nullif(p_status,''),'På lager'),coalesce(nullif(p_color,''),'#5B7FBE'),coalesce(p_notes,'')) returning id into v_id;
  else
    update public.bookings set order_no=nullif(btrim(p_order_no),''),customer_name=nullif(btrim(p_customer_name),''),title=nullif(btrim(p_title),''),start_date=p_start_date,end_date=p_end_date,delivery_date=p_delivery_date,pickup_date=p_pickup_date,status=coalesce(nullif(p_status,''),'På lager'),color=coalesce(nullif(p_color,''),'#5B7FBE'),notes=coalesce(p_notes,''),updated_at=now() where id=p_id;
    if not found then raise exception 'Ordren findes ikke'; end if; v_id:=p_id;
  end if;
  delete from public.booking_tents where booking_id=v_id;
  insert into public.booking_tents(booking_id,tent_id,quantity)
  select v_id,x.tent_id,greatest(1,coalesce(x.quantity,1)) from jsonb_to_recordset(coalesce(p_tents,'[]'::jsonb)) as x(tent_id bigint,quantity integer)
  where exists(select 1 from public.tents t where t.id=x.tent_id);
  delete from public.booking_inventory where booking_id=v_id;
  insert into public.booking_inventory(booking_id,inventory_id,quantity)
  select v_id,x.inventory_id,greatest(1,coalesce(x.quantity,1)) from jsonb_to_recordset(coalesce(p_inventory,'[]'::jsonb)) as x(inventory_id bigint,quantity integer)
  where exists(select 1 from public.inventory i where i.id=x.inventory_id);
  return v_id;
end;
$$;

