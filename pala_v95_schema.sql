create or replace function public.employee_change_own_pin(p_token text, p_current_pin text, p_new_pin text)
returns void
language plpgsql security definer set search_path = public, pg_temp
as $$
declare v_id bigint; v_hash text;
begin
  select s.employee_id into v_id from public.employee_sessions s join public.employees e on e.id=s.employee_id where s.token=p_token and s.expires_at>now() and e.active limit 1;
  if v_id is null then raise exception 'Ugyldig eller udløbet medarbejdersession'; end if;
  if p_new_pin !~ '^[0-9]{4,8}$' then raise exception 'Den nye kode skal være 4-8 cifre'; end if;
  select pin_hash into v_hash from public.employee_credentials where employee_id=v_id;
  if extensions.crypt(coalesce(p_current_pin,''),v_hash) <> v_hash then raise exception 'Den nuværende kode er forkert'; end if;
  update public.employee_credentials set pin_hash=extensions.crypt(p_new_pin,extensions.gen_salt('bf')),updated_at=now() where employee_id=v_id;
  delete from public.employee_sessions where employee_id=v_id and token<>p_token;
end;
$$;

create or replace function public.admin_save_employee(p_token text, p_id bigint, p_name text, p_is_admin boolean)
returns bigint
language plpgsql security definer set search_path = public, pg_temp
as $$
declare v_admin record; v_id bigint; v_can_manage_admin boolean;
begin
  select * into v_admin from public.pala_session_employee(p_token) limit 1;
  if v_admin.employee_id is null or not v_admin.is_admin then raise exception 'Administratorlogin kræves'; end if;
  v_can_manage_admin := lower(btrim(v_admin.employee_name))='lukas';
  if btrim(coalesce(p_name,''))='' then raise exception 'Medarbejderen skal have et navn'; end if;
  if p_id is null then
    insert into public.employees(name,is_admin,sort_order)
    values(btrim(p_name),case when v_can_manage_admin then coalesce(p_is_admin,false) else false end,(select coalesce(max(sort_order),0)+1 from public.employees))
    returning id into v_id;
    insert into public.employee_credentials(employee_id,pin_hash) values(v_id,extensions.crypt('4211',extensions.gen_salt('bf')));
  else
    if not exists(select 1 from public.employees where id=p_id) then raise exception 'Medarbejderen findes ikke'; end if;
    if v_can_manage_admin then
      if p_id=v_admin.employee_id and coalesce(p_is_admin,false)=false then raise exception 'Lukas kan ikke fjerne sin egen adminstatus'; end if;
      update public.employees set name=btrim(p_name),is_admin=coalesce(p_is_admin,false),updated_at=now() where id=p_id;
    else
      update public.employees set name=btrim(p_name),updated_at=now() where id=p_id;
    end if;
    v_id:=p_id;
  end if;
  return v_id;
end;
$$;

