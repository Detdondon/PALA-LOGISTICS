as $$
declare v_admin record; v_id bigint;
begin
  select * into v_admin from public.pala_session_employee(p_token) limit 1;
  if v_admin.employee_id is null or not v_admin.is_admin then raise exception 'Administratorlogin kræves'; end if;
  if p_shift_date is null then raise exception 'Vælg dato for vagten'; end if;
  if p_id is null then
