create or replace function public.admin_invite_staffing(p_token text,p_shift_id bigint,p_employee_ids jsonb)
returns integer
language plpgsql security definer set search_path = public, pg_temp
as $$
declare v_admin record; v_booking_id bigint; v_count integer;
begin
  select * into v_admin from public.pala_session_employee(p_token) limit 1;
  if v_admin.employee_id is null or not v_admin.is_admin then raise exception 'Administratorlogin kræves'; end if;
  select booking_id into v_booking_id from public.staffing_shifts where id=p_shift_id;
  if not found then raise exception 'Vagten findes ikke'; end if;
  insert into public.staffing_invitations(booking_id,shift_id,employee_id,status,created_by_employee_id)
  select v_booking_id,p_shift_id,(value #>> '{}')::bigint,'pending',v_admin.employee_id from jsonb_array_elements(coalesce(p_employee_ids,'[]'::jsonb))
  where exists(select 1 from public.employees e where e.id=(value #>> '{}')::bigint and e.active)
  on conflict(shift_id,employee_id) do update set status='pending',created_by_employee_id=excluded.created_by_employee_id,created_at=now(),responded_at=null;
  get diagnostics v_count=row_count; return v_count;
end;
$$;

