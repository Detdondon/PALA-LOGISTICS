create or replace function public.booking_checklist_summaries()
returns table(booking_id bigint,hardware_total integer,hardware_packed integer,tent_total integer,tent_packed integer,inventory_total integer,inventory_packed integer,total_required integer,total_packed integer,total_returned integer)
language sql stable security definer set search_path = public, pg_temp
as $$
  select b.id,
    coalesce(sum(l.qty_required) filter(where l.line_type='hardware'),0)::integer,
    coalesce(sum(least(l.qty_required,coalesce(p.packed_qty,0))) filter(where l.line_type='hardware'),0)::integer,
    coalesce(sum(l.qty_required) filter(where l.line_type='tent'),0)::integer,
    coalesce(sum(least(l.qty_required,coalesce(p.packed_qty,0))) filter(where l.line_type='tent'),0)::integer,
    coalesce(sum(l.qty_required) filter(where l.line_type='inventory'),0)::integer,
    coalesce(sum(least(l.qty_required,coalesce(p.packed_qty,0))) filter(where l.line_type='inventory'),0)::integer,
    coalesce(sum(l.qty_required),0)::integer,
