  else insert into public.tent_notes(tent_id,note,updated_by_employee_id) values(p_tent_id,btrim(p_note),v_employee.employee_id)
    on conflict(tent_id) do update set note=excluded.note,updated_by_employee_id=excluded.updated_by_employee_id,updated_at=now(); end if;
end $$;

create or replace function public.employee_workshop_tasks(p_token text)
returns table(id bigint,tent_id bigint,tent_name text,booking_id bigint,booking_name text,description text,status text,completion_note text,created_by_employee_id bigint,created_by_employee_name text,completed_by_employee_id bigint,completed_by_employee_name text,created_at timestamptz,updated_at timestamptz,completed_at timestamptz)
language plpgsql security definer set search_path = public, pg_temp
as $$ declare v_employee record; begin
  select * into v_employee from public.pala_session_employee(p_token) limit 1; if v_employee.employee_id is null then raise exception 'Medarbejderlogin kræves'; end if;
  return query select w.id,w.tent_id,t.name,w.booking_id,coalesce(b.customer_name,b.title,b.order_no),w.description,w.status,w.completion_note,w.created_by_employee_id,ce.name,w.completed_by_employee_id,de.name,w.created_at,w.updated_at,w.completed_at
  from public.tent_workshop_tasks w join public.tents t on t.id=w.tent_id left join public.bookings b on b.id=w.booking_id left join public.employees ce on ce.id=w.created_by_employee_id left join public.employees de on de.id=w.completed_by_employee_id
  order by (w.status='open') desc,w.created_at desc,w.id desc;
end $$;

create or replace function public.employee_report_tent_damage(p_token text,p_tent_id bigint,p_booking_id bigint,p_description text)
returns bigint language plpgsql security definer set search_path = public, pg_temp
as $$ declare v_employee record; v_id bigint; begin
  select * into v_employee from public.pala_session_employee(p_token) limit 1; if v_employee.employee_id is null then raise exception 'Medarbejderlogin kræves'; end if;
  if btrim(coalesce(p_description,''))='' then raise exception 'Beskriv skaden'; end if;
  insert into public.tent_workshop_tasks(tent_id,booking_id,description,created_by_employee_id) values(p_tent_id,p_booking_id,btrim(p_description),v_employee.employee_id) returning id into v_id; return v_id;
end $$;

create or replace function public.employee_set_workshop_task_status(p_token text,p_task_id bigint,p_completed boolean,p_completion_note text default '')
returns void language plpgsql security definer set search_path = public, pg_temp
as $$ declare v_employee record; begin
  select * into v_employee from public.pala_session_employee(p_token) limit 1; if v_employee.employee_id is null then raise exception 'Medarbejderlogin kræves'; end if;
  update public.tent_workshop_tasks set status=case when p_completed then 'completed' else 'open' end,completion_note=case when p_completed then btrim(coalesce(p_completion_note,'')) else '' end,completed_by_employee_id=case when p_completed then v_employee.employee_id else null end,completed_at=case when p_completed then now() else null end,updated_at=now() where id=p_task_id;
  if not found then raise exception 'Systueopgaven findes ikke'; end if;
end $$;

