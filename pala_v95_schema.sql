create or replace function public.pala_session_employee(p_token text)
returns table(employee_id bigint, employee_name text, is_admin boolean)
language sql
security definer
set search_path = public, pg_temp
as $$
  select e.id, e.name, e.is_admin
  from public.employee_sessions s
  join public.employees e on e.id = s.employee_id
  where s.token = p_token and s.expires_at > now() and e.active = true
  limit 1
$$;

create or replace function public.employee_validate(p_token text)
returns table(token text, employee_id bigint, employee_name text, is_admin boolean, expires_at timestamptz)
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  delete from public.employee_sessions where expires_at <= now();
  update public.employee_sessions set expires_at = greatest(expires_at, now() + interval '30 days') where employee_sessions.token = p_token;
  return query
  select s.token, e.id, e.name, e.is_admin, s.expires_at
  from public.employee_sessions s join public.employees e on e.id = s.employee_id
  where s.token = p_token and s.expires_at > now() and e.active = true limit 1;
end;
$$;

create or replace function public.employee_login(p_employee_id bigint, p_pin text)
returns table(token text, employee_id bigint, employee_name text, is_admin boolean, expires_at timestamptz)
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare v_employee public.employees%rowtype; v_credential public.employee_credentials%rowtype; v_token text; v_expires timestamptz;
begin
  select * into v_employee from public.employees where id = p_employee_id and active = true for update;
  if v_employee.id is null then return; end if;
  select c.* into v_credential from public.employee_credentials c where c.employee_id=p_employee_id;
  if v_credential.pin_hash is null or extensions.crypt(coalesce(p_pin,''), v_credential.pin_hash) <> v_credential.pin_hash then
    return;
  end if;
  v_token := gen_random_uuid()::text; v_expires := now() + interval '30 days';
  insert into public.employee_sessions(token,employee_id,expires_at) values(v_token,p_employee_id,v_expires);
  return query select v_token, v_employee.id, v_employee.name, v_employee.is_admin, v_expires;
end;
$$;

