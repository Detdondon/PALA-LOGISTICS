create or replace function public.order_checklist_get(p_access_token text)
returns jsonb
language plpgsql security definer set search_path = public, pg_temp
as $$
declare v_booking_id bigint; v_order jsonb; v_lines jsonb;
begin
  select booking_id into v_booking_id from public.order_access_tokens where token=p_access_token and expires_at>now();
  if v_booking_id is null then raise exception 'Pakkelinket er ugyldigt eller udløbet'; end if;
  select to_jsonb(b) into v_order from public.bookings b where b.id=v_booking_id;
  select coalesce(jsonb_agg(jsonb_build_object(
    'id',l.id,'line_type',l.line_type,'item_id',l.item_id,'parent_tent_id',nullif(l.parent_tent_id,0),'item_name',l.item_name,'description',l.description,'qty_required',l.qty_required,
    'packed_qty',least(l.qty_required,coalesce(p.packed_qty,0)),'returned_qty',least(l.qty_required,coalesce(p.returned_qty,0)),
    'drying_required_qty',case when l.line_type='tent' then least(l.qty_required,coalesce(p.drying_required_qty,0)) else 0 end,
    'dried_qty',case when l.line_type='tent' then least(l.qty_required,coalesce(p.dried_qty,0)) else 0 end
  ) order by case l.line_type when 'tent' then 1 when 'hardware' then 2 else 3 end,l.parent_tent_id,l.item_name),'[]'::jsonb)
  into v_lines from public.pala_order_lines(v_booking_id) l left join public.order_checklist_progress p on p.booking_id=v_booking_id and p.line_type=l.line_type and p.item_id=l.item_id and p.parent_tent_id=l.parent_tent_id;
  return jsonb_build_object('order',v_order,'lines',v_lines);
end $$;

create or replace function public.order_checklist_change(p_access_token text,p_line_id bigint,p_phase text,p_delta integer,p_set_all boolean)
returns void
language plpgsql security definer set search_path = public, pg_temp
as $$
declare v_booking_id bigint; v_line record; v_packed integer; v_returned integer;
begin
  select booking_id into v_booking_id from public.order_access_tokens where token=p_access_token and expires_at>now(); if v_booking_id is null then raise exception 'Pakkelinket er ugyldigt eller udløbet'; end if;
  select * into v_line from public.pala_order_lines(v_booking_id) where id=p_line_id; if v_line.id is null then raise exception 'Linjen findes ikke'; end if;
  select coalesce(packed_qty,0),coalesce(returned_qty,0) into v_packed,v_returned from public.order_checklist_progress where booking_id=v_booking_id and line_type=v_line.line_type and item_id=v_line.item_id and parent_tent_id=v_line.parent_tent_id;
  if p_phase='returned' then v_returned:=case when p_set_all then v_line.qty_required else greatest(0,least(v_line.qty_required,coalesce(v_returned,0)+coalesce(p_delta,0))) end; v_packed:=greatest(coalesce(v_packed,0),v_returned);
  elsif p_phase='packed' then v_packed:=case when p_set_all then v_line.qty_required else greatest(v_returned,least(v_line.qty_required,coalesce(v_packed,0)+coalesce(p_delta,0))) end;
  else raise exception 'Ukendt pakkefase'; end if;
  insert into public.order_checklist_progress(booking_id,line_type,item_id,parent_tent_id,packed_qty,returned_qty)
  values(v_booking_id,v_line.line_type,v_line.item_id,v_line.parent_tent_id,v_packed,v_returned)
  on conflict(booking_id,line_type,item_id,parent_tent_id) do update set packed_qty=excluded.packed_qty,returned_qty=excluded.returned_qty,updated_at=now();
end $$;

