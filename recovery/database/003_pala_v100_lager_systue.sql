    values(trim(p_title),coalesce(p_customer_name,''),coalesce(p_address,''),p_start_date,p_end_date,coalesce(nullif(p_status,''),'Planlagt'),coalesce(nullif(p_color,''),'#6C8EBF'),coalesce(p_notes,''),v_employee_id)
