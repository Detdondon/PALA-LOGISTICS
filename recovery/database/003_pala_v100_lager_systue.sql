create or replace function public.pala_v100_emit_sync_event()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  insert into public.pala_sync_events(source) values (tg_table_name);
  delete from public.pala_sync_events
  where changed_at < now() - interval '7 days';
  return null;
end;
$$;

revoke all on function public.pala_v100_emit_sync_event() from public, anon, authenticated;

do $$
declare t text;
begin
  foreach t in array array['tent_parts','special_hardware','special_hardware_tents','workshop_jobs','workshop_job_documents','staff_leave_requests'] loop
    execute format('drop trigger if exists pala_v100_sync_event on public.%I', t);
    execute format('create trigger pala_v100_sync_event after insert or update or delete on public.%I for each statement execute function public.pala_v100_emit_sync_event()', t);
  end loop;
end $$;

