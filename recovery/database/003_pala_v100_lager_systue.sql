create or replace function public.employee_request_leave(p_token text,p_leave_type text,p_start_date date,p_end_date date)
returns bigint
language plpgsql
security definer
set search_path=public,pg_temp
as $$
declare v_employee_id bigint;v_id bigint;
begin
  v_employee_id:=public.pala_v100_employee_id(p_token,false);
  if p_leave_type not in ('Ferie','Ude') or p_start_date is null or p_end_date is null or p_end_date<p_start_date then raise exception 'Fraværsperioden er ugyldig.'; end if;
