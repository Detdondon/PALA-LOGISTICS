create or replace function public.admin_respond_leave_request(p_token text,p_request_id bigint,p_approve boolean)
returns void language plpgsql security definer set search_path=public,pg_temp
as $$
declare
  v_admin_id bigint;
  v_request public.staff_leave_requests%rowtype;
  v_employee_name text;
  v_marker text;
begin
  v_admin_id:=public.pala_v100_employee_id(p_token,true);
  select * into v_request
  from public.staff_leave_requests
  where id=p_request_id and status='pending'
  for update;
  if not found then raise exception 'Fraværsanmodningen findes ikke eller er allerede besvaret.'; end if;

  if p_approve then
    select name into v_employee_name from public.employees where id=v_request.employee_id;
    v_marker:=format(
      '[PALA-FRAVAER employee=%s end=%s type=%s]',
      v_request.employee_id,
      v_request.end_date,
      v_request.leave_type
    );
    if not exists (
      select 1 from public.staffing_shifts s
      where s.notes like '%'||v_marker||'%'
    ) then
      insert into public.staffing_shifts(
        booking_id,shift_date,start_time,end_time,workers_needed,title,notes,
        daily_leader_employee_id,created_by_employee_id
      ) values (
        null,v_request.start_date,null,null,1,
        v_request.leave_type||' · '||coalesce(v_employee_name,'Medarbejder'),
        v_marker,null,v_admin_id
      );
    end if;
  end if;

  update public.staff_leave_requests
  set status=case when p_approve then 'approved' else 'declined' end,
      responded_at=now(),
      responded_by_employee_id=v_admin_id
  where id=p_request_id;
end;
$$;

create or replace function public.admin_save_special_hardware(
  p_token text,
  p_id bigint,
