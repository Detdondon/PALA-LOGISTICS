as $$
declare v_id bigint;
begin
  perform public.pala_v100_employee_id(p_token,true);
  insert into public.workshop_job_documents(workshop_job_id,title,file_name,mime_type,file_data)
  values(p_workshop_job_id,trim(p_title),p_file_name,coalesce(p_mime_type,'application/octet-stream'),p_file_data) returning id into v_id;
  return v_id;
end;
$$;

