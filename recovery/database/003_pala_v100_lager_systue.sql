create or replace function public.admin_save_tent_parts(p_token text, p_tent_id bigint, p_parts jsonb)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  perform public.pala_v100_employee_id(p_token, true);
  if not exists (select 1 from public.tents where id = p_tent_id) then raise exception 'Teltet findes ikke.'; end if;
  delete from public.tent_parts where tent_id = p_tent_id;
  insert into public.tent_parts(tent_id, name, description, qty, optional, sort_order)
  select p_tent_id,
         trim(coalesce(x->>'name','')),
         coalesce(x->>'description',''),
         greatest(1, coalesce((x->>'qty')::integer,1)),
         coalesce((x->>'optional')::boolean,true),
         coalesce((x->>'sort_order')::integer,0)
  from jsonb_array_elements(coalesce(p_parts,'[]'::jsonb)) x
  where trim(coalesce(x->>'name','')) <> '';
end;
$$;

create or replace function public.admin_save_hardware_categories(p_token text, p_tent_id bigint, p_categories jsonb)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare x jsonb;
begin
  perform public.pala_v100_employee_id(p_token, true);
  for x in select * from jsonb_array_elements(coalesce(p_categories,'[]'::jsonb)) loop
    update public.hardware h
    set category = coalesce(nullif(trim(x->>'category'),''),'Standard hardware'),
        material = coalesce(x->>'material',''),
        length_m = nullif(x->>'length_m','')::numeric
    where h.tent_id = p_tent_id
      and case
        when nullif(x->>'id','') is not null then h.id = (x->>'id')::bigint
        else h.sort_order = coalesce((x->>'sort_order')::integer,0) and h.name = coalesce(x->>'name','')
      end;
  end loop;
end;
$$;

create or replace function public.admin_set_shift_assignments(p_token text,p_shift_id bigint,p_employee_ids bigint[])
returns void
language plpgsql
security definer
set search_path=public,pg_temp
as $$
begin
  perform public.pala_v100_employee_id(p_token,true);
  if not exists(select 1 from public.staffing_shifts where id=p_shift_id) then raise exception 'Vagten findes ikke.'; end if;
  delete from public.staffing_assignments a
  where a.shift_id=p_shift_id and not (a.employee_id=any(coalesce(p_employee_ids,'{}'::bigint[])));
  insert into public.staffing_assignments(shift_id,employee_id)
  select p_shift_id,e.id
  from public.employees e
  where e.active is true
    and e.id=any(coalesce(p_employee_ids,'{}'::bigint[]))
    and not exists(select 1 from public.staffing_assignments a where a.shift_id=p_shift_id and a.employee_id=e.id);
end;
$$;

create or replace function public.admin_configure_shift_staff(
  p_token text,
  p_shift_id bigint,
  p_direct_employee_ids bigint[],
  p_request_employee_ids bigint[]
)
returns void
language plpgsql
security definer
set search_path=public,pg_temp
as $$
declare
  v_admin_id bigint;
  v_booking_id bigint;
begin
  v_admin_id:=public.pala_v100_employee_id(p_token,true);
  select booking_id into v_booking_id
  from public.staffing_shifts
  where id=p_shift_id;
  if not found then raise exception 'Vagten findes ikke.'; end if;

  delete from public.staffing_assignments a
  where a.shift_id=p_shift_id
    and not (a.employee_id=any(coalesce(p_direct_employee_ids,'{}'::bigint[])));

  insert into public.staffing_assignments(shift_id,employee_id)
  select p_shift_id,e.id
  from public.employees e
  where e.active is true
    and e.id=any(coalesce(p_direct_employee_ids,'{}'::bigint[]))
  on conflict do nothing;

  -- Direkte tilknytning og "ikke valgt" må ikke efterlade en gammel forespørgsel.
  delete from public.staffing_invitations i
  where i.shift_id=p_shift_id
    and (
      i.employee_id=any(coalesce(p_direct_employee_ids,'{}'::bigint[]))
      or not (i.employee_id=any(coalesce(p_request_employee_ids,'{}'::bigint[])))
    );

  insert into public.staffing_invitations(
    booking_id,shift_id,employee_id,status,created_by_employee_id,created_at,responded_at
  )
  select v_booking_id,p_shift_id,e.id,'pending',v_admin_id,now(),null
  from public.employees e
  where e.active is true
    and e.id=any(coalesce(p_request_employee_ids,'{}'::bigint[]))
    and not (e.id=any(coalesce(p_direct_employee_ids,'{}'::bigint[])))
  on conflict(shift_id,employee_id) do update
    set booking_id=excluded.booking_id,
        status='pending',
        created_by_employee_id=excluded.created_by_employee_id,
        created_at=now(),
        responded_at=null;
end;
$$;

