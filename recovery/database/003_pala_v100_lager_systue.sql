  p_address text,
  p_start_date date,
  p_end_date date,
  p_status text,
  p_color text,
  p_notes text
)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare v_employee_id bigint; v_id bigint;
begin
  v_employee_id:=public.pala_v100_employee_id(p_token,true);
  if trim(coalesce(p_title,''))='' then raise exception 'Jobnavn mangler.'; end if;
  if p_start_date is null or p_end_date is null or p_end_date<p_start_date then raise exception 'Datoerne er ugyldige.'; end if;
