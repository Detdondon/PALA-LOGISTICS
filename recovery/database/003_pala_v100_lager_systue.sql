create or replace function public.pala_v100_employee_id(p_token text, p_admin boolean default false)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare v_employee_id bigint;
begin
  select e.id into v_employee_id
  from public.employee_sessions s
  join public.employees e on e.id = s.employee_id
  where s.token = p_token
    and e.active is true
    and (s.expires_at is null or s.expires_at > now())
    and (not p_admin or e.is_admin is true)
  limit 1;
  if v_employee_id is null then
    raise exception 'Login er udløbet eller mangler de nødvendige rettigheder.';
  end if;
  return v_employee_id;
end;
$$;

