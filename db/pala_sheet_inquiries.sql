revoke all on function public.admin_sheet_inquiry_create_booking(text,bigint,date,date,date,date) from public;
grant execute on function public.admin_sheet_inquiries(text) to anon, authenticated;
grant execute on function public.admin_sheet_inquiry_review(text,bigint,text) to anon, authenticated;
grant execute on function public.admin_sheet_inquiry_create_booking(text,bigint,date,date,date,date) to anon, authenticated;
