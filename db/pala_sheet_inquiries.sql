create table if not exists public.pala_sheet_inquiries (
  id bigint generated by default as identity primary key,
  source_sheet_id text not null,
  source_tab_id integer not null,
  source_tab_name text not null,
  source_row integer not null check (source_row > 0),
  source_month text not null default '',
  customer_name text not null,
  phone text not null default '',
  address text not null default '',
  description text not null default '',
  use_date_text text not null default '',
  delivery_date_text text not null default '',
  pickup_date_text text not null default '',
  reserved boolean not null default false,
  quote_given boolean not null default false,
  order_sent boolean not null default false,
  in_logistics_calendar boolean not null default false,
  review_status text not null default 'pending' check (review_status in ('pending','imported','ignored')),
  booking_id bigint references public.bookings(id) on delete set null,
  source_fingerprint text not null default '',
  last_seen_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(source_sheet_id,source_tab_id,source_row)
);
create index if not exists pala_sheet_inquiries_status_idx on public.pala_sheet_inquiries(review_status,source_row);
alter table public.pala_sheet_inquiries enable row level security;
revoke all on public.pala_sheet_inquiries from anon, authenticated;
revoke all on sequence public.pala_sheet_inquiries_id_seq from anon, authenticated;

create or replace function public.admin_sheet_inquiries(p_token text)
returns setof public.pala_sheet_inquiries
language plpgsql security definer
set search_path to 'public','pg_temp'
as $fn$
begin
  if not exists (
    select 1 from public.pala_session_employee(p_token) s
    where s.employee_id is not null and s.is_admin
  ) then
    raise exception 'Administratorlogin kræves';
  end if;
  return query select i.* from public.pala_sheet_inquiries i
    order by i.source_row, i.id;
end;
$fn$;

create or replace function public.admin_sheet_inquiry_review(
  p_token text, p_import_id bigint, p_action text
)
returns boolean
language plpgsql security definer
set search_path to 'public','pg_temp'
as $fn$
begin
  if not exists (
    select 1 from public.pala_session_employee(p_token) s
    where s.employee_id is not null and s.is_admin
  ) then
    raise exception 'Administratorlogin kræves';
  end if;
  if p_action not in ('ignore','restore') then
    raise exception 'Ugyldig handling';
  end if;
  update public.pala_sheet_inquiries
  set review_status = case when p_action = 'ignore' then 'ignored' else 'pending' end,
      updated_at = now()
  where id = p_import_id and booking_id is null;
  if not found then raise exception 'Forespørgslen findes ikke eller er allerede importeret'; end if;
  return true;
end;
$fn$;

create or replace function public.admin_sheet_inquiry_create_booking(
  p_token text,
  p_import_id bigint,
  p_start_date date,
  p_end_date date,
  p_delivery_date date default null,
  p_pickup_date date default null
)
returns bigint
language plpgsql security definer
set search_path to 'public','pg_temp'
as $fn$
declare v record; v_booking_id bigint; v_notes text;
begin
  if not exists (
    select 1 from public.pala_session_employee(p_token) s
    where s.employee_id is not null and s.is_admin
  ) then
    raise exception 'Administratorlogin kræves';
  end if;
  if p_start_date is null or p_end_date is null or p_end_date < p_start_date then
    raise exception 'Angiv og kontrollér brugsperioden';
  end if;
  select * into v from public.pala_sheet_inquiries where id = p_import_id for update;
  if not found then raise exception 'Forespørgslen findes ikke'; end if;
  if v.booking_id is not null then return v.booking_id; end if;
  if v.review_status = 'ignored' then raise exception 'Gendan forespørgslen før import'; end if;

  v_notes := concat_ws(E'\n',
    'Kilde: Google Sheet "' || v.source_tab_name || '", række ' || v.source_row,
    'Brugsdato i arket: ' || coalesce(nullif(v.use_date_text,''),'ikke angivet'),
    case when v.address <> '' then 'Adresse: ' || v.address end,
    case when v.phone <> '' then 'Telefon: ' || v.phone end
  );
  v_booking_id := public.admin_save_booking(
    p_token,
    null,
    null,
    v.customer_name,
    coalesce(nullif(v.description,''),'Teltforespørgsel – ' || v.customer_name),
    p_start_date,
    p_end_date,
    p_delivery_date,
    p_pickup_date,
    'Forespørgsel',
    '#5B7FBE',
    v_notes,
    '[]'::jsonb,
    '[]'::jsonb
  );
  update public.pala_sheet_inquiries
  set review_status='imported', booking_id=v_booking_id, updated_at=now()
  where id=p_import_id;
  return v_booking_id;
end;
$fn$;

revoke all on function public.admin_sheet_inquiries(text) from public;
